const fs=require('fs'),vm=require('vm'),assert=require('assert');
const c={console,Map,Set,Object,Array,String,Number,Boolean,RegExp,JSON,Math,Date};c.globalThis=c;vm.createContext(c);
const load=f=>vm.runInContext(fs.readFileSync(f,'utf8'),c,{filename:f});
load('src/repository/repository-policy.js');
load('src/intelligence/repository-evidence-contract.js');
load('src/intelligence/repository-chunker.js');
const C=c.CodeeRepositoryChunker;
assert.equal(C.capability().authority,false);assert.equal(C.capability().plan_advance,false);
const content=Array.from({length:12},(_,i)=>`line-${i+1} `+'x'.repeat(48)).join('\n');
const a=C.chunkFile('./src/a.js',content,{maxChars:128,overlapLines:1});
assert.ok(a.length>=3,'bounded content should split into multiple chunks');
assert.equal(a[0].path,'src/a.js');assert.equal(a[0].start_line,1);assert.equal(a[0].deterministic,true);assert.equal(a[0].confidence,1);
assert.equal(a[1].start_line,a[0].end_line,'one-line overlap should be retained');
const again=C.chunkFile('./src/a.js',content,{maxChars:128,overlapLines:1});
assert.equal(a[0].chunk_id,again[0].chunk_id,'chunk IDs must be stable');
const redacted=C.chunkFile('src/secret.js','const api_key = "abcdefghijklmnopqrstuvwxyz123456";\nnext();',{maxChars:500});
assert.ok(!redacted[0].text.includes('abcdefghijklmnopqrstuvwxyz123456'),'chunk text should use repository redaction');
const snap=C.chunkSnapshot({files:{'src/b.js':'b1\nb2','src/a.js':'a1\na2'}},{maxChars:128,maxChunks:1});
assert.equal(snap.length,1);assert.equal(snap[0].path,'src/a.js','snapshot chunking must be path-deterministic');
const ev=C.toEvidence(a,{limit:2});assert.equal(ev.length,2);assert.equal(ev[0].source_kind,'repository.chunk');assert.equal(ev[0].authority,false);assert.equal(ev[0].confidence,1);
assert.throws(()=>C.chunkFile('',content),e=>e.code==='ERR_REPOSITORY_CHUNK_PATH');
console.log('PASS repository chunker');
