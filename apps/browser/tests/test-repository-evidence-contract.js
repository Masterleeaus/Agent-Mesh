const fs=require('fs'),vm=require('vm'),assert=require('assert');
const c={console,Map,Set,Object,Array,String,Number,Boolean,RegExp,JSON,Math,Date};c.globalThis=c;vm.createContext(c);
const load=f=>vm.runInContext(fs.readFileSync(f,'utf8'),c,{filename:f});
load('src/repository/repository-policy.js');
load('src/intelligence/repository-evidence-contract.js');
const C=c.CodeeRepositoryEvidenceContract;
assert.equal(C.capability().authority,false);
assert.equal(C.capability().plan_advance,false);
const search=C.fromSearch({matches:[{path:'./src/a.js',line:3,text:'const token = "secret";'}]});
assert.equal(search.length,1);assert.equal(search[0].path,'src/a.js');assert.equal(search[0].deterministic,true);assert.equal(search[0].confidence,1);assert.equal(search[0].authority,false);
const symbols=C.fromSymbols({symbols:[{path:'src/a.js',line:2,name:'Alpha',kind:'class'}]});
assert.equal(symbols[0].symbol,'Alpha');
const deps=C.fromDependencies({edges:[{from:'src/a.js',to:'src/b.js',symbol:'Beta',type:'reference'}]});
assert.equal(deps[0].source_kind,'repository.dependency');
const again=C.fromSearch({matches:[{path:'src/a.js',line:3,text:'const token = "secret";'}]});
assert.equal(search[0].evidence_id,again[0].evidence_id,'evidence IDs must be deterministic');
const merged=C.merge([search,again,symbols,deps]);assert.equal(merged.length,3,'duplicate evidence must collapse');
const model=C.normalizeEvidence({source_kind:'model.summary',text:'hypothesis',deterministic:false,confidence:3});
assert.equal(model.confidence,1);assert.equal(model.advisory_only,true);assert.equal(model.canonical,false);assert.equal(model.mutation_authorized,false);
assert.throws(()=>C.normalizeEvidence({}),e=>e.code==='ERR_REPOSITORY_EVIDENCE_EMPTY');
console.log('PASS repository evidence contract');
