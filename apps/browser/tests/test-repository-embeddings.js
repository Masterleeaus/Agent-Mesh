'use strict';
const fs=require('fs');const vm=require('vm');const assert=require('assert');const path=require('path');
const root=path.join(__dirname,'..');
const ctx={console};ctx.globalThis=ctx;vm.createContext(ctx);
for(const file of ['src/repository/repository-policy.js','src/intelligence/repository-embeddings.js']) vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
(async()=>{
 const API=ctx.CodeeRepositoryEmbeddings;
 assert.ok(API&&API.RepositoryEmbeddings,'embeddings API exposed');
 const fallback=new API.RepositoryEmbeddings({dimensions:32});
 const a=await fallback.embed([{id:'a',text:'Repository search symbol dependency graph'}]);
 const b=await fallback.embed([{id:'a',text:'Repository search symbol dependency graph'}]);
 assert.equal(a.length,1);assert.equal(a[0].dimensions,32);assert.equal(a[0].vector.length,32);
 assert.equal(a[0].provider,'deterministic-lexical-hash');assert.equal(a[0].local,true);assert.equal(a[0].deterministic,true);assert.equal(a[0].degraded,true);
 assert.equal(a[0].authority,false);assert.equal(a[0].canonical,false);assert.deepEqual(a[0].vector,b[0].vector,'fallback vector stable');
 const calls=[];
 const remote={name:'remote',local:false,embed:async texts=>{calls.push('remote');return texts.map(()=>[0,1,0,0]);}};
 const local={name:'local',local:true,model:'tiny-local',embed:async texts=>{calls.push('local');return {vectors:texts.map(()=>[1,0,0,0]),backend:'wasm',local:true};}};
 const preferred=new API.RepositoryEmbeddings({providers:[remote,local],dimensions:16});
 const p=await preferred.embed(['alpha beta']);
 assert.deepEqual(calls,['local'],'local provider preferred');assert.equal(p[0].provider,'local');assert.equal(p[0].local,true);assert.equal(p[0].degraded,false);assert.equal(p[0].dimensions,16);
 const failLocal={name:'broken-local',local:true,embed:async()=>{const e=new Error('down');e.code='DOWN';throw e;}};
 const failover=new API.RepositoryEmbeddings({providers:[remote,failLocal],dimensions:16});calls.length=0;
 const f=await failover.embed(['gamma']);assert.deepEqual(calls,['remote']);assert.equal(f[0].provider,'remote');
 const localOnly=new API.RepositoryEmbeddings({providers:[remote],dimensions:16});calls.length=0;
 const l=await localOnly.embed(['delta'],{localOnly:true});assert.equal(l[0].provider,'deterministic-lexical-hash');assert.equal(l[0].fallback_reason,'no_provider_available');assert.deepEqual(calls,[]);
 const strict=new API.RepositoryEmbeddings({providers:[failLocal],allowDeterministicFallback:false});
 await assert.rejects(()=>strict.embed(['x']),e=>e.code==='ERR_REPOSITORY_EMBEDDING_UNAVAILABLE');
 const cap=preferred.capability();assert.equal(cap.local_first,true);assert.equal(cap.authority,false);assert.equal(cap.max_batch,128);
 console.log('PASS repository embeddings local-first provider-neutral contract');
})().catch(err=>{console.error(err);process.exit(1);});
