const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const sw = fs.readFileSync(path.join(root, 'src/lib/service-worker.js'), 'utf8');
const ui = fs.readFileSync(path.join(root, 'src/sidebar/sidebar.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'src/sidebar/sidebar.html'), 'utf8');
const content = fs.readFileSync(path.join(root, 'src/content-script.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
function ok(v,m){ if(!v) throw new Error(m); }
const versionParts=manifest.version.split('.').map(Number);
ok(versionParts[0] > 2 || (versionParts[0]===2 && (versionParts[1] > 11 || (versionParts[1]===11 && versionParts[2] >= 1))), 'manifest version must be >= 2.11.1');
ok(sw.includes("NEXT_RUNNER_ALARM_PREFIX = 'CODEE_NEXT_RUNNER:'"), 'standalone alarm prefix missing');
ok(sw.includes("message.action === 'START_NEXT_RUNNER'"), 'start action missing');
ok(sw.includes("message.action === 'UPDATE_NEXT_RUNNER_INTERVAL'"), 'interval update action missing');
ok(sw.includes("message.action === 'STOP_NEXT_RUNNER'"), 'stop action missing');
ok(sw.includes("const immediate = await sendStandaloneNext(tabId);"), 'start must send next immediately');
ok(sw.includes('captureNextRunnerTarget(tabId)'), 'start must bind the exact target conversation');
ok(sw.includes('resolveNextRunnerTarget(tabId, bound.target)'), 'every send must resolve and re-verify the exact bound target');
ok(sw.includes("source:'existing-target-tab'"), 'runner must recover the exact target from another open tab');
ok(sw.includes("source:'opened-target-tab'"), 'runner must be able to reopen the canonical exact target in the background');
ok(sw.includes("reason:'target-conversation-mismatch'"), 'conversation mismatch must be blocked');
ok(sw.includes('liveIdentity !== expectedIdentity'), 'runner must compare live and bound conversation identity');
const nextRunnerTargetFunction = ui.match(/function getNextRunnerTargetTabId\(\) \{[\s\S]*?\n\}/)?.[0] || '';
ok(nextRunnerTargetFunction.includes("const raw = document.getElementById?.('tab-select')?.value;"), 'Next Runner target must come from explicit selection');
ok(!nextRunnerTargetFunction.includes('activeConversationTabId') && !nextRunnerTargetFunction.includes('currentTabId'), 'Next Runner must not fall back to active/current conversation');
ok(sw.includes("periodInMinutes:minutes"), 'repeating alarm cadence missing');
ok(sw.includes('restoreNextRunnerAlarms()'), 'startup alarm restoration missing');
ok(html.includes('id="next-runner-start-btn"'), 'start button missing');
ok(html.includes('id="next-runner-minutes"'), 'interval input missing');
ok(html.includes('id="next-runner-apply-btn"'), 'apply timer button missing');
ok(html.includes('id="next-runner-stop-btn"'), 'stop button missing');
ok(ui.includes("action:'START_NEXT_RUNNER'"), 'UI start action missing');
ok(ui.includes("action:'UPDATE_NEXT_RUNNER_INTERVAL'"), 'UI timer update action missing');
ok(content.includes("reason:'composer-not-empty'"), 'draft protection must remain');
console.log('PASS standalone Next Runner compatibility >= v2.11.1');
