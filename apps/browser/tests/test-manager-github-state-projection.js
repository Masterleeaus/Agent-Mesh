const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..'),s={console};s.globalThis=s;vm.createContext(s);
vm.runInContext(fs.readFileSync(path.join(root,'src/titan-zero/manager-github-state-projection.js'),'utf8'),s,{filename:'manager-github-state-projection'});
const G=s.TitanCodeManagerGitHubStateProjection, main='a'.repeat(40), base='a'.repeat(40), head='b'.repeat(40);
assert.strictEqual(G.branchFor('SG04'),'agent/SG04');
let x=G.derive({subgoalId:'SG04',mainSha:main,issue:{number:722,state:'open',subgoalId:'SG04'}});
assert.strictEqual(x.state,'AVAILABLE');assert.strictEqual(x.authority,'github');
x=G.derive({subgoalId:'SG04',mainSha:main,baseSha:base,headSha:base,issue:{number:722,state:'open'},branch:{exists:true}});
assert.strictEqual(x.state,'CLAIMED');
x=G.derive({subgoalId:'SG04',mainSha:main,baseSha:base,headSha:head,issue:{number:722,state:'open'},branch:{exists:true}});
assert.strictEqual(x.state,'ACTIVE');
x=G.derive({subgoalId:'SG04',mainSha:main,baseSha:base,headSha:head,issue:{number:722,state:'open'},branch:{exists:true},pr:{state:'open'},checks:[{required:true,status:'in_progress'}]});
assert.strictEqual(x.state,'VERIFYING');
x=G.derive({subgoalId:'SG04',mainSha:main,baseSha:base,headSha:head,issue:{number:722,state:'open'},branch:{exists:true},pr:{state:'open'},checks:[{required:true,conclusion:'success'}]});
assert.strictEqual(x.state,'READY');
x=G.derive({subgoalId:'SG04',mainSha:main,baseSha:base,headSha:head,issue:{number:722,state:'closed'},branch:{exists:true},pr:{state:'closed',merged:true},checks:[{required:true,conclusion:'success'}]});
assert.strictEqual(x.state,'COMPLETED');
assert.throws(()=>G.derive({subgoalId:'SG04',mainSha:'not-a-sha',issue:{state:'open'}}),/valid GitHub main SHA/);
console.log('PASS test-manager-github-state-projection');
